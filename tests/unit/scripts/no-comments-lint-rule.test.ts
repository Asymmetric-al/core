describe("comment ban scope", () => {
  it.each([
    "apps/admin/app/page.tsx",
    "packages/auth/middleware.ts",
    "scripts/verify/index.mjs",
    "tooling/eslint-config/base.mjs",
    "tests/unit/utils.test.ts",
    "playwright.config.ts",
  ])("covers %s", (file) => {
    expect(inCommentBanScope(file)).toBe(true);
  });

  it.each([
    "docs/prds/tools/render.mjs",
    "vendor/react-pdf-packages/index.js",
    ".agents/skills/x/scripts/run.mjs",
    "tests/fixtures/sample/input.ts",
    "apps/factory-console/tests/fixtures/scale-fixture.ts",
    "apps/admin/payload-types.ts",
    "apps/admin/app/(payload)/web-studio/importMap.js",
    "apps/admin/src/migrations/20261117_040437_upload_state.ts",
    "apps/donor/bones/registry.ts",
    "apps/donor/public/maplibre/worker.js",
    "packages/database/types/currency-foundation.generated.ts",
    "scripts/archon-factory/pack/index.mjs",
    "packages/auth/README.md",
    "../outside.ts",
  ])("leaves out %s", (file) => {
    expect(inCommentBanScope(file)).toBe(false);
  });
});

describe("bannedComments", () => {
  it("keeps prose and drops machine-read comments", () => {
    const comments = [
      { type: "Line", value: " prettier-ignore" },
      { type: "Line", value: " why this exists" },
      { type: "Block", value: "* @deprecated Use next. " },
      { type: "Block", value: " global window " },
      { type: "Line", value: " global window is patched below" },
      { type: "Shebang", value: "/usr/bin/env node" },
    ];
    expect(
      bannedComments(comments, "scripts/tool.mjs").map(
        (comment: { value: string }) => comment.value,
      ),
    ).toEqual([" why this exists", " global window is patched below"]);
  });
});

describe("the rule in the shared configuration", () => {
  it("names the baseline it reads", () => {
    expect(commentBaselineFile).toBe(
      "tooling/eslint-config/comment-baseline.json",
    );
    expect(Object.keys(noCommentsPlugin.rules)).toEqual(["no-comments"]);
  });

  it.each([
    ["the root configuration", ".", "packages/auth/probe-comment.ts"],
    ["a library workspace", "packages/auth", "probe-comment.ts"],
    ["an app workspace", "apps/donor", "lib/probe-comment.ts"],
  ])("is an error through %s", async (_name, workspace, file) => {
    const cwd = path.join(root, workspace);
    const eslint = new ESLint({
      cwd,
      overrideConfig: {
        languageOptions: { parserOptions: { projectService: false } },
      },
    });
    const [result] = await eslint.lintText(
      "// a new comment\nexport const probe = 1;\n",
      { filePath: path.join(cwd, file) },
    );
    expect(
      result?.messages
        .filter((message) => message.ruleId === "core/no-comments")
        .map((message) => message.severity),
    ).toEqual([2]);
  });
});
