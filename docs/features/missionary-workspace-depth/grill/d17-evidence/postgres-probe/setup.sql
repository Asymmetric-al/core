CREATE FUNCTION probe.tenant() RETURNS int LANGUAGE sql STABLE SET search_path=pg_catalog AS $$ SELECT CASE WHEN session_user IN('missionary_a','staff_a','worker_a','worker_b','policy_manager') THEN 1 ELSE -1 END $$;
