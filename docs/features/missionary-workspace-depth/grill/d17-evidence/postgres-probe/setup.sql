CREATE FUNCTION probe.preview(p_plan int) RETURNS text LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,probe,pg_temp AS $$
BEGIN
 IF NOT EXISTS(SELECT 1 FROM probe.plans p JOIN probe.sessions s ON (s.tenant,s.id)=(p.tenant,p.session) JOIN probe.gates g ON (g.tenant,g.workspace,g.actor)=(s.tenant,s.workspace,s.actor) WHERE p.tenant=probe.tenant() AND p.id=p_plan AND s.actor=probe.actor() AND g.allowed) THEN RETURN 'unavailable'; END IF;
 RETURN (SELECT count(*)::text FROM probe.rows WHERE tenant=probe.tenant() AND plan=p_plan);
END $$;
CREATE FUNCTION probe.approve(p_session int,p_plan int,p_revision int) RETURNS text LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,probe,pg_temp AS $$
DECLARE s probe.sessions%ROWTYPE; p probe.plans%ROWTYPE; g probe.gates%ROWTYPE;
BEGIN
 SELECT * INTO p FROM probe.plans WHERE tenant=probe.tenant() AND id=p_plan AND session=p_session;
 IF NOT FOUND THEN RETURN 'unavailable'; END IF;
 SELECT * INTO g FROM probe.gates WHERE tenant=p.tenant AND workspace=p.workspace AND actor=probe.actor() FOR SHARE;
 IF NOT FOUND OR NOT g.allowed THEN RETURN 'unavailable'; END IF;
 SELECT * INTO s FROM probe.sessions WHERE tenant=p.tenant AND id=p_session AND actor=probe.actor() FOR UPDATE;
 IF NOT FOUND THEN RETURN 'unavailable'; END IF;
 IF s.state<>'preview' OR s.current_plan<>p_plan OR s.revision<>p_revision OR p.authority_revision<>g.revision THEN RETURN 'conflict'; END IF;
 UPDATE probe.sessions SET state='approved',revision=revision+1 WHERE tenant=s.tenant AND id=s.id;
 RETURN 'approved';
END $$;
CREATE FUNCTION probe.cancel(p_session int) RETURNS text LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,probe,pg_temp AS $$
BEGIN
 UPDATE probe.sessions SET state='cancelled',revision=revision+1 WHERE tenant=probe.tenant() AND id=p_session AND actor=session_user AND state<>'cancelled';
 IF FOUND THEN RETURN 'cancelled'; ELSE RETURN 'unavailable'; END IF;
END $$;

CREATE FUNCTION probe.claim(p_plan int,p_row int) RETURNS text LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,probe,pg_temp AS $$
DECLARE p probe.plans%ROWTYPE; s probe.sessions%ROWTYPE; g probe.gates%ROWTYPE; j probe.jobs%ROWTYPE;
BEGIN
 SELECT * INTO p FROM probe.plans WHERE tenant=probe.tenant() AND id=p_plan;
 IF NOT FOUND THEN RETURN 'unavailable'; END IF;
 SELECT * INTO g FROM probe.gates WHERE tenant=p.tenant AND workspace=p.workspace AND actor=probe.actor() FOR SHARE;
 IF NOT FOUND OR NOT g.allowed OR p.authority_revision<>g.revision THEN RETURN 'unavailable'; END IF;
 SELECT * INTO s FROM probe.sessions WHERE tenant=p.tenant AND id=p.session AND actor=probe.actor() FOR SHARE;
 IF NOT FOUND OR s.state<>'approved' OR s.current_plan<>p_plan THEN RETURN 'unavailable'; END IF;
 SELECT * INTO j FROM probe.jobs WHERE tenant=p.tenant AND plan=p_plan AND row_number=p_row FOR UPDATE;
 IF NOT FOUND THEN RETURN 'unavailable'; END IF;
 IF j.done THEN RETURN 'done'; END IF;
 IF j.lease_until>clock_timestamp() THEN RETURN 'busy'; END IF;
 UPDATE probe.jobs SET epoch=epoch+1,worker=session_user,lease_until=clock_timestamp()+interval '5 minutes' WHERE tenant=p.tenant AND plan=p_plan AND row_number=p_row RETURNING epoch INTO j.epoch;
 RETURN 'lease:'||j.epoch;
END $$;

CREATE FUNCTION probe.apply_row(p_plan int,p_row int,p_epoch int) RETURNS text LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,probe,pg_temp AS $$
DECLARE p probe.plans%ROWTYPE; s probe.sessions%ROWTYPE; g probe.gates%ROWTYPE; j probe.jobs%ROWTYPE; r probe.rows%ROWTYPE; k probe.source_keys%ROWTYPE; target_version int; target_id bigint; result text;
BEGIN
 SELECT * INTO p FROM probe.plans WHERE tenant=probe.tenant() AND id=p_plan;
 IF NOT FOUND THEN RETURN 'unavailable'; END IF;
 SELECT * INTO g FROM probe.gates WHERE tenant=p.tenant AND workspace=p.workspace AND actor=probe.actor() FOR SHARE;
 IF NOT FOUND OR NOT g.allowed OR p.authority_revision<>g.revision THEN RETURN 'unavailable'; END IF;
 SELECT * INTO s FROM probe.sessions WHERE tenant=p.tenant AND id=p.session AND actor=probe.actor() FOR SHARE;
 IF NOT FOUND OR s.state<>'approved' OR s.current_plan<>p_plan THEN RETURN 'unavailable'; END IF;
 SELECT * INTO j FROM probe.jobs WHERE tenant=p.tenant AND plan=p_plan AND row_number=p_row FOR UPDATE;
 IF NOT FOUND THEN RETURN 'unavailable'; END IF;
 IF j.epoch<>p_epoch OR j.worker IS DISTINCT FROM session_user OR j.lease_until IS NULL OR j.lease_until<=clock_timestamp() THEN RETURN 'stale_lease'; END IF;
 IF j.done THEN RETURN (SELECT status FROM probe.outcomes WHERE tenant=p.tenant AND plan=p_plan AND row_number=p_row); END IF;
 SELECT * INTO r FROM probe.rows WHERE tenant=p.tenant AND plan=p_plan AND row_number=p_row;
 IF r.decision='review' THEN result:='needs_review';
 ELSIF r.target IS NOT NULL THEN
  SELECT revision INTO target_version FROM probe.preparation WHERE (tenant,workspace,id)=(p.tenant,p.workspace,r.target) FOR UPDATE;
  IF NOT FOUND OR target_version<>r.target_revision THEN result:='target_conflict'; END IF;
 END IF;
 IF result IS NULL THEN
  INSERT INTO probe.source_keys VALUES(p.tenant,p.workspace,p.source_namespace,r.source_id,NULL,NULL) ON CONFLICT DO NOTHING;
  SELECT * INTO k FROM probe.source_keys WHERE (tenant,workspace,source_namespace,source_id)=(p.tenant,p.workspace,p.source_namespace,r.source_id) FOR UPDATE;
  IF r.target IS NOT NULL AND (k.target IS NULL OR k.target<>r.target) THEN result:='target_conflict';
  ELSIF k.target IS NOT NULL THEN
   IF k.payload=r.payload THEN result:='already_imported';target_id:=k.target;
   ELSE result:='needs_review'; END IF;
  ELSE
   INSERT INTO probe.preparation(tenant,workspace,actor,payload,revision) VALUES(p.tenant,p.workspace,probe.actor(),r.payload,1) RETURNING id INTO target_id;
   UPDATE probe.source_keys SET target=target_id,payload=r.payload WHERE (tenant,workspace,source_namespace,source_id)=(p.tenant,p.workspace,p.source_namespace,r.source_id);
   result:='accepted';
  END IF;
 END IF;
 IF target_id IS NOT NULL THEN INSERT INTO probe.provenance VALUES(p.tenant,p_plan,p_row,p.workspace,p.source_namespace,r.source_id,target_id,r.audit_note); END IF;
 IF j.lease_until<=clock_timestamp() THEN RAISE EXCEPTION 'fixture lease expired before acceptance' USING ERRCODE='40001'; END IF;
 INSERT INTO probe.outcomes VALUES(p.tenant,p_plan,p_row,p.workspace,result,target_id);
 UPDATE probe.jobs SET done=true WHERE tenant=p.tenant AND plan=p_plan AND row_number=p_row;
 RETURN result;
END $$;
-- Stand-in for an independently authorized owner edit; changes revision only.
CREATE FUNCTION probe.touch_target(p_target bigint) RETURNS text LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,probe,pg_temp AS $$
BEGIN
 UPDATE probe.preparation SET revision=revision+1 WHERE tenant=probe.tenant() AND workspace=10 AND id=p_target AND actor=session_user;
 IF FOUND THEN RETURN 'edited'; ELSE RETURN 'unavailable'; END IF;
END $$;
