CREATE TABLE probe.sessions(tenant int,id int,workspace int,actor text NOT NULL,current_plan int NOT NULL,revision int NOT NULL,state text NOT NULL CHECK(state IN('preview','approved','cancelled')),PRIMARY KEY(tenant,id),UNIQUE(tenant,id,workspace));
CREATE TABLE probe.plans(tenant int,id int,session int,workspace int,byte_digest text NOT NULL,mapping_version int NOT NULL,source_namespace text NOT NULL CHECK(source_namespace<>''),authority_revision int NOT NULL,PRIMARY KEY(tenant,id),UNIQUE(tenant,id,workspace),FOREIGN KEY(tenant,session,workspace) REFERENCES probe.sessions(tenant,id,workspace));
ALTER TABLE probe.sessions ADD CONSTRAINT current_plan_fk FOREIGN KEY(tenant,current_plan,workspace) REFERENCES probe.plans(tenant,id,workspace) DEFERRABLE INITIALLY DEFERRED;
CREATE TABLE probe.preparation(tenant int,workspace int,id bigint GENERATED BY DEFAULT AS IDENTITY,actor text NOT NULL,payload jsonb NOT NULL,revision int NOT NULL,PRIMARY KEY(tenant,workspace,id));
CREATE TABLE probe.rows(tenant int,plan int,workspace int,row_number int,source_id text NOT NULL CHECK(source_id<>''),payload jsonb NOT NULL,decision text NOT NULL CHECK(decision IN('eligible','review')),target bigint,target_revision int,audit_note text NOT NULL,PRIMARY KEY(tenant,plan,row_number),UNIQUE(tenant,plan,source_id),FOREIGN KEY(tenant,plan,workspace) REFERENCES probe.plans(tenant,id,workspace),FOREIGN KEY(tenant,workspace,target) REFERENCES probe.preparation,CHECK((target IS NULL)=(target_revision IS NULL)));
CREATE TABLE probe.jobs(tenant int,plan int,row_number int,epoch int NOT NULL DEFAULT 0,worker text,lease_until timestamptz,done boolean NOT NULL DEFAULT false,PRIMARY KEY(tenant,plan,row_number),FOREIGN KEY(tenant,plan,row_number) REFERENCES probe.rows);
CREATE TABLE probe.source_keys(tenant int,workspace int,source_namespace text,source_id text,target bigint,payload jsonb,PRIMARY KEY(tenant,workspace,source_namespace,source_id),UNIQUE(tenant,workspace,source_namespace,source_id,target),FOREIGN KEY(tenant,workspace,target) REFERENCES probe.preparation,CHECK((target IS NULL)=(payload IS NULL)));
CREATE TABLE probe.provenance(tenant int,plan int,row_number int,workspace int,source_namespace text,source_id text,target bigint NOT NULL,note text NOT NULL CHECK(note<>'FAIL_FIXTURE_AUDIT'),PRIMARY KEY(tenant,plan,row_number),FOREIGN KEY(tenant,plan,row_number) REFERENCES probe.rows,FOREIGN KEY(tenant,workspace,source_namespace,source_id,target) REFERENCES probe.source_keys(tenant,workspace,source_namespace,source_id,target));
CREATE TABLE probe.outcomes(tenant int,plan int,row_number int,workspace int NOT NULL,status text NOT NULL CHECK(status IN('accepted','already_imported','needs_review','target_conflict')),target bigint,PRIMARY KEY(tenant,plan,row_number),FOREIGN KEY(tenant,plan,row_number) REFERENCES probe.rows,FOREIGN KEY(tenant,plan,workspace) REFERENCES probe.plans(tenant,id,workspace),FOREIGN KEY(tenant,workspace,target) REFERENCES probe.preparation);
CREATE TABLE probe.dark_effects(tenant int,id int,effect text NOT NULL,PRIMARY KEY(tenant,id));
